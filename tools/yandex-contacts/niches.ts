const pad = (n: number) => String(n).padStart(2, '0');

export const NICHES: Niche[] = GROUPS.flatMap(([group, items], g) =>
  items.map(([title, queries], i) => ({code: `${pad(g + 1)}-${pad(i + 1)}`, group, title, queries})));

const norm = (s: string) => s.toLowerCase().replaceAll('ё', 'е').trim();

/**
 * Niches matching any filter: `4` (whole group), `4-2` / `04-02` / `4.2`
 * (one niche) or part of a niche or group name. No filters selects all.
 */
export function selectNiches(filters: string[], niches: Niche[] = NICHES): Niche[] {
  if (!filters.length) return niches;
  const picked = new Set<Niche>();
  for (const f of filters) {
    const num = f.trim().match(/^(\d+)(?:[-.](\d+))?$/);
    const matches = niches.filter(n => {
      if (!num) return norm(n.title).includes(norm(f)) || norm(n.group).includes(norm(f));
      const [g, i] = n.code.split('-').map(Number);
      return g === Number(num[1]) && (num[2] === undefined || i === Number(num[2]));
    });
    if (!matches.length) throw new Error(`ниша «${f}» не найдена (список: --list)`);
    for (const n of matches) picked.add(n);
  }
  return niches.filter(n => picked.has(n));
}
